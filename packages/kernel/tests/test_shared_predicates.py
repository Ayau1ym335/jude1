"""UT/property tests of the exact predicates (XC-SHR-01, TD-04).

Completion criterion: 100 % agreement with a rational (``fractions.Fraction``) oracle on the
adversarial set T13 (>= 10**5 cases per predicate), and identical results over 100 runs.

T13 is the frozen fixture set of XC-SHR-03 (tests/fixtures/T13): the inputs are regenerated by
``jude_fixtures.t13`` and must match their frozen SHA-256; the expected signs were computed once
by the Fraction oracle and are committed.
"""

