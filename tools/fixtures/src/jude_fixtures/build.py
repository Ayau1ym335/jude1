"""Build or verify the synthetic fixtures (FN-OPS-06, TSK-OPS-06-C).

    jude-fixtures build [--out tests/fixtures] [--sets T1,T3]   write files + manifest
    jude-fixtures check [--out tests/fixtures] [--sets ...]     regenerate in memory and compare
                                                                with manifest.json (exit 1 on drift)

Layout: ``<out>/<set>/<name>.json`` (analytic truth, always committed),
``<out>/<set>/<name>/<file>`` (mesh files), ``<out>/manifest.json`` (SHA-256 and size of every
file). Files larger than ``COMMIT_LIMIT`` are listed in the manifest but not committed
(.gitignore); ``build`` writes them locally and ``check`` verifies them by hash, so the bytes
are pinned either way.
"""

import argparse
from collections.abc import Iterable
import hashlib
import json
from pathlib import Path
import sys
from typing import Any

from jude_fixtures.sets import SETS, Fixture

SCHEMA = "fixtures/1"
COMMIT_LIMIT = 1_100_000  # bytes; larger files are regenerated, not committed
DEFAULT_OUT = Path("tests/fixtures")


def _json(doc: Any) -> bytes:
    return (json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def collect(sets: Iterable[str]) -> list[Fixture]:
    out: list[Fixture] = []
    for name in sets:
        out += SETS[name]()
    return out


def manifest_entry(fx: Fixture) -> dict[str, Any]:
    return {
        "set": fx.set,
        "params": fx.params,
        "seed": fx.seed,
        "truth": f"{fx.set}/{fx.name}.json",
        "truth_sha256": hashlib.sha256(_json(fx.truth)).hexdigest(),
        "files": {
            fname: {
                "path": f"{fx.set}/{fx.name}/{fname}",
                "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
                "committed": len(data) <= COMMIT_LIMIT,
            }
            for fname, data in sorted(fx.files.items())
        },
    }


def build(out: Path, sets: list[str]) -> dict[str, Any]:
    fixtures = collect(sets)
    manifest_path = out / "manifest.json"
    manifest: dict[str, Any] = (
        json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest_path.exists()
        else {"schema": SCHEMA, "fixtures": {}}
    )
    for fx in fixtures:
        entry = manifest_entry(fx)
        (out / fx.set).mkdir(parents=True, exist_ok=True)
        (out / entry["truth"]).write_bytes(_json(fx.truth))
        for fname, data in fx.files.items():
            path = out / entry["files"][fname]["path"]
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        manifest["fixtures"][fx.id] = entry
    manifest["fixtures"] = dict(sorted(manifest["fixtures"].items()))
    manifest_path.write_bytes(_json(manifest))
    _write_gitignore(out, manifest)
    return manifest


def _write_gitignore(out: Path, manifest: dict[str, Any]) -> None:
    large = sorted(
        f["path"]
        for e in manifest["fixtures"].values()
        for f in e["files"].values()
        if not f["committed"]
    )
    text = (
        "# Generated by `jude-fixtures build`: large fixtures are pinned by hash, not committed.\n"
    )
    body = text + "".join(f"/{p}\n" for p in large)
    (out / ".gitignore").write_text(body, encoding="utf-8", newline="\n")


def check(out: Path, sets: list[str]) -> list[str]:
    """Problems found when the fixtures are regenerated and compared with the manifest."""
    manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    problems = []
    seen = set()
    for fx in collect(sets):
        seen.add(fx.id)
        want = manifest["fixtures"].get(fx.id)
        if want is None:
            problems.append(f"{fx.id}: not in manifest.json")
            continue
        got = manifest_entry(fx)
        if got != want:
            problems.append(f"{fx.id}: regenerated fixture differs from manifest.json")
        truth = out / got["truth"]
        if not truth.exists() or truth.read_bytes() != _json(fx.truth):
            problems.append(f"{fx.id}: analytic JSON {got['truth']} missing or stale")
        for fname, meta in got["files"].items():
            path = out / meta["path"]
            if meta["committed"] and (not path.exists() or path.read_bytes() != fx.files[fname]):
                problems.append(f"{fx.id}: committed file {meta['path']} missing or stale")
    for fid, entry in manifest["fixtures"].items():
        if entry["set"] in sets and fid not in seen:
            problems.append(f"{fid}: in manifest.json but no longer generated")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="jude-fixtures", description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["build", "check"])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--sets", default=",".join(SETS), help="comma-separated, e.g. T1,T3")
    args = parser.parse_args(argv)
    sets = [s.strip() for s in args.sets.split(",") if s.strip()]
    unknown = sorted(set(sets) - set(SETS))
    if unknown:
        parser.error(f"unknown sets: {', '.join(unknown)}")
    if args.command == "build":
        manifest = build(args.out, sets)
        print(f"wrote {len(manifest['fixtures'])} fixtures to {args.out}")
        return 0
    problems = check(args.out, sets)
    for p in problems:
        print(f"FIXTURE {p}")
    if problems:
        print("regenerate with `jude-fixtures build` and review the diff", file=sys.stderr)
        return 1
    print(f"fixtures {','.join(sets)}: reproducible, manifest matches")
    return 0


if __name__ == "__main__":
    sys.exit(main())
